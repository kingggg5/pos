@Injectable({ providedIn: 'root' })
export class I18nService {
	readonly locale = signal<AppLocale>(
		(localStorage.getItem('pos_locale') as AppLocale) || 'en'
	);

	readonly isThaiLocale = computed(() => this.locale() === 'th');

	translate(key: string): string {
		const dictionary = this.locale() === 'th' ? TH : EN;
		return dictionary[key] ?? key;
	}

	toggleLocale(): void {
		const next = this.locale() === 'en' ? 'th' : 'en';
		this.locale.set(next);
		localStorage.setItem('pos_locale', next);
	}
}
